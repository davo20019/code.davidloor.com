#!/usr/bin/env node
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import yaml from "js-yaml";

const PROBLEMS_ROOT = path.resolve(process.cwd(), "problems");
const LEARN_ROOT = path.resolve(process.cwd(), "learn");
const PROBLEMS_OUT = path.resolve(process.cwd(), "lib/problems/manifest.ts");
const LEARN_OUT = path.resolve(process.cwd(), "lib/learn/manifest.ts");

async function readDirSafe(p) {
  try {
    return await readdir(p, { withFileTypes: true });
  } catch {
    return [];
  }
}

async function loadCoding(dir) {
  const id = path.basename(dir);
  const meta = yaml.load(await readFile(path.join(dir, "meta.yaml"), "utf8"));
  const statementMarkdown = await readFile(path.join(dir, "problem.md"), "utf8");
  const starterPython = await readFile(path.join(dir, "starter.py"), "utf8");
  const starterJs = await readFile(path.join(dir, "starter.js"), "utf8");
  const solutionPython = await readFile(path.join(dir, "solution.py"), "utf8");
  const solutionJs = await readFile(path.join(dir, "solution.js"), "utf8");
  const tests = JSON.parse(await readFile(path.join(dir, "tests.json"), "utf8"));
  return {
    type: "coding",
    meta: { id, ...meta },
    statementMarkdown,
    starters: { python: starterPython, javascript: starterJs },
    solutions: { python: solutionPython, javascript: solutionJs },
    tests,
  };
}

async function loadSystemDesign(dir) {
  const id = path.basename(dir);
  const meta = yaml.load(await readFile(path.join(dir, "meta.yaml"), "utf8"));
  const promptMarkdown = await readFile(path.join(dir, "problem.md"), "utf8");
  return { type: "system_design", meta: { id, ...meta }, promptMarkdown };
}

async function loadLearn(dir) {
  const id = path.basename(dir);
  const meta = yaml.load(await readFile(path.join(dir, "meta.yaml"), "utf8"));
  const contentMarkdown = await readFile(path.join(dir, "content.md"), "utf8");
  return { type: "learn", meta: { id, ...meta }, contentMarkdown };
}

// --- problems manifest ---

const codingDirs = (await readDirSafe(path.join(PROBLEMS_ROOT, "coding"))).filter((d) => d.isDirectory());
const sysDirs = (await readDirSafe(path.join(PROBLEMS_ROOT, "system-design"))).filter((d) => d.isDirectory());
const coding = await Promise.all(
  codingDirs.map((d) => loadCoding(path.join(PROBLEMS_ROOT, "coding", d.name))),
);
const sys = await Promise.all(
  sysDirs.map((d) => loadSystemDesign(path.join(PROBLEMS_ROOT, "system-design", d.name))),
);

const allProblems = [...coding, ...sys];
const problemsBody = `// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.
import type { Problem } from "./types";
export const problems: Problem[] = ${JSON.stringify(allProblems, null, 2)} as const;
export const codingProblems = problems.filter((p) => p.type === "coding");
export const systemDesignProblems = problems.filter((p) => p.type === "system_design");
`;
await writeFile(PROBLEMS_OUT, problemsBody, "utf8");

// --- learn manifest ---

const learnDirs = (await readDirSafe(LEARN_ROOT)).filter((d) => d.isDirectory());
const learn = await Promise.all(learnDirs.map((d) => loadLearn(path.join(LEARN_ROOT, d.name))));
const learnBody = `// AUTO-GENERATED by scripts/build-manifest.mjs — do not edit by hand.
import type { LearnGuide } from "./types";
export const learnGuides: LearnGuide[] = ${JSON.stringify(learn, null, 2)} as const;
`;
await writeFile(LEARN_OUT, learnBody, "utf8");

console.log(
  `Wrote manifests: ${coding.length} coding, ${sys.length} system-design, ${learn.length} learn guides.`,
);
